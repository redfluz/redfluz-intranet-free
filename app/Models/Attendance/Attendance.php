namespace App\Models\Attendance;

use App\Models\System\User;
use Carbon\CarbonInterface;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Table;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Spatie\Activitylog\Models\Activity;
use Spatie\Activitylog\Models\Concerns\HasActivity;
use Spatie\Activitylog\Support\LogOptions;

/**
 * @mixin Builder<Attendance>
 *
 * @property string $id
 * @property string $user_id
 * @property CarbonInterface $work_date
 * @property CarbonInterface|null $clock_in
 * @property CarbonInterface|null $clock_out
 * @property int $worked_minutes
 * @property string|null $notes
 * @property CarbonInterface|null $deleted_at
 * @property CarbonInterface $created_at
 * @property CarbonInterface $updated_at
 *
 * @noinspection PhpUnused
 *
 * @property-read User|null $user
 * @property-read Collection<int, Activity> $activities
 * @property-read Collection<int, Activity> $activitiesAsCauser
 * @property-read Collection<int, Activity> $activitiesAsSubject
 */
#[Table('attendances', key: 'id')]
#[Fillable(['user_id', 'work_date', 'clock_in', 'clock_out', 'worked_minutes', 'notes'])]
class Attendance extends Model
{
    use HasActivity, HasUuids, SoftDeletes;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'work_date' => 'date',
            'clock_in' => 'datetime',
            'clock_out' => 'datetime',
            'worked_minutes' => 'integer',
        ];
    }

    /**
     * Define an inverse one-to-one or many relationship.
     * Get the user that owns the attendance record.
     *
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Recalculate worked minutes from the recorded clock-in and clock-out times.
     *
     * A record without both timestamps has zero completed worked minutes.
     */
    public function recalculateWorkedMinutes(): void
    {
        $this->worked_minutes = $this->clock_in && $this->clock_out
            ? (int) max(0, $this->clock_in->diffInMinutes($this->clock_out))
            : 0;
    }

    /**
     * Get the options for logging activity using Spatie Activitylog.
     *
     * @return LogOptions Returns configured log options.
     */
    public function getActivitylogOptions(): LogOptions
    {
        return LogOptions::defaults()->logFillable()->logOnlyDirty();
    }
}
