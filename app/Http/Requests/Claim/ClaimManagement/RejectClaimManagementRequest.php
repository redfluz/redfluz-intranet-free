declare(strict_types=1);

namespace App\Http\Requests\Claim\ClaimManagement;

use App\Enums\FileAction;
use App\Enums\FileResources;

/**
 * The fields a claim is rejected with.
 */
class RejectClaimManagementRequest extends ClaimManagementRequest
{
    /**
     * Who may reject a claim.
     */
    public function authorize(): bool
    {
        return $this->allows(FileResources::CLAIM_MANAGEMENTS, FileAction::CANCEL);
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'rejection_reason' => ['required', 'string', 'max:1000'],
        ];
    }
}
